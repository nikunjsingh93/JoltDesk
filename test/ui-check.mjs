import { _electron, expect } from '@playwright/test';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { startServer } from '../server.mjs';
import { mockProvider, testModel } from './mock-provider.mjs';
const dir=path.resolve('work/ui-'+Date.now()),provider=await mockProvider();provider.setDelay(35);
await fs.mkdir(path.join(dir,'agent'),{recursive:true});
await fs.writeFile(path.join(dir,'agent','models.json'),JSON.stringify({providers:{openai:{baseUrl:provider.url,models:[testModel]}}}));
const originalFetch=globalThis.fetch;
globalThis.fetch=(url,opts)=>String(url)==='https://api.openai.com/v1/models'?Promise.resolve(new Response(JSON.stringify({data:[{id:'bolt-test'}]}),{headers:{'Content-Type':'application/json'}})):originalFetch(url,opts);
const server=await startServer({dataDir:dir,autoStartUpdates:false});
const env={...process.env,BOLT_TEST_URL:server.url};delete env.ELECTRON_RUN_AS_NODE;
let app;const errors=[];
try{
  app=await _electron.launch({args:['test/ui-shell.cjs'],env});const page=await app.firstWindow();
  page.on('pageerror',e=>errors.push(e.message));
  await expect(page.locator('h1')).toContainText('A little spark.');
  await page.locator('#settings').click();await page.locator('#api-key').fill('sk-test-not-real');await page.locator('#connect-button').click();
  await expect(page.locator('#settings-dialog')).not.toBeVisible();await expect(page.locator('#model')).toHaveValue('bolt-test');
  await page.locator('#prompt').fill('Show me a formatted JavaScript example.');await page.locator('#send').click();
  await expect(page.locator('#send')).toHaveClass(/running/);
  await expect(page.locator('.thinking-body')).toContainText('I will check');
  await expect(page.locator('#context')).toContainText('32,000');
  await expect(page.locator('#send')).not.toHaveClass(/running/,{timeout:20000});
  await expect(page.locator('.markdown pre code')).toContainText('Hello, Bolt');
  await expect(page.locator('.hljs-keyword').first()).toBeVisible();
  await expect(page.locator('.reply-metrics [data-stat="tokens"]').last()).toContainText('42');await expect(page.locator('#context')).toContainText('162');
  await page.evaluate(()=>{Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async value=>{window.__copiedPrompt=value;}}});});
  await page.locator('.message.user [data-prompt-action="copy"]').first().click();
  await expect.poll(()=>page.evaluate(()=>window.__copiedPrompt)).toBe('Show me a formatted JavaScript example.');
  await page.locator('.message.user [data-prompt-action="edit"]').first().click();
  await expect(page.locator('#prompt')).toHaveValue('Show me a formatted JavaScript example.');
  await page.locator('#prompt').fill('');
  await page.screenshot({path:'work/screenshots/joltdesk-preview.png'});
  await page.locator('#permission').selectOption('ask');await expect(page.locator('#permission')).toHaveValue('ask');
  provider.tool('write',{path:'ui-approved.txt',content:'approved from UI'});
  await page.locator('#prompt').fill('Write the file after I approve.');await page.locator('#send').click();
  await expect(page.locator('#approval-dialog')).toBeVisible();await page.waitForTimeout(1600);await page.locator('#allow').click();
  await expect(page.locator('#send')).not.toHaveClass(/running/,{timeout:20000});
  const total=await page.locator('.reply-metrics [data-stat="time"]').last().textContent();if(parseFloat(total)<1.5)throw new Error('Turn time did not include approval wait: '+total);
  if(await fs.readFile(path.join(dir,'workspace','ui-approved.txt'),'utf8')!=='approved from UI')throw new Error('UI approval did not execute tool');
  await page.locator('#theme').click();await expect(page.locator('body')).toHaveClass(/light/);await page.locator('#theme').click();
  await page.setViewportSize({width:420,height:850});await expect(page.locator('#send')).toBeVisible();await page.screenshot({path:'work/mobile-layout.png'});
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('UI PASS: key setup, model discovery, streaming thinking/text, token/context stats, code highlighting, tool approval, themes and mobile layout.');
}finally{await app?.close();server.close();provider.close();globalThis.fetch=originalFetch;}
